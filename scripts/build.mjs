import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = async (p) => JSON.parse(await readFile(resolve(root, p), 'utf8'));
export const cssName = (name) => `--cb-${name.replaceAll('.', '-')}`;
export function validateTheme(theme) {
  const expected = Object.keys(theme.appearance.light).sort().join();
  for (const [name, values] of Object.entries(theme.appearance)) {
    if (Object.keys(values).sort().join() !== expected)
      throw Error(`Appearance keys differ: ${name}`);
  }
  const density = Object.keys(theme.density.comfortable).sort().join();
  for (const [name, values] of Object.entries(theme.density)) {
    if (Object.keys(values).sort().join() !== density)
      throw Error(`Density keys differ: ${name}`);
  }
}
export async function generate() {
  const base = await read('design-system/tokens/base.json');
  const theme = await read('design-system/themes/macos/tokens.json');
  validateTheme(theme);
  const names = [
    ...Object.keys(base.tokens),
    ...Object.keys(theme.material),
    ...Object.keys(theme.appearance.light),
    ...Object.keys(theme.density.comfortable),
  ];
  if (new Set(names.map(cssName)).size !== names.length)
    throw Error('CSS token name collision');
  const block = (selector, values) =>
    `${selector} {\n${Object.entries(values)
      .map(([k, v]) => `  ${cssName(k)}: ${v};`)
      .join('\n')}\n}\n`;
  const banner =
    '/* Generated by scripts/build.mjs. Edit token sources instead. */\n';
  let css = banner + block(':root', { ...base.tokens, ...theme.material });
  css += block(':root, [data-appearance="light"]', theme.appearance.light);
  css += block('[data-appearance="dark"]', theme.appearance.dark);
  css += block(
    ':root, [data-density="comfortable"]',
    theme.density.comfortable,
  );
  css += block('[data-density="compact"]', theme.density.compact);
  const colors = Object.keys(theme.appearance.light).filter(
    (k) => !k.startsWith('material.'),
  );
  const mappings = Object.fromEntries(
    colors.map((k) => [
      `--color-${k.replaceAll('.', '-')}`,
      `var(${cssName(k)})`,
    ]),
  );
  for (const k of Object.keys(base.tokens).filter((k) =>
    k.startsWith('space.'),
  ))
    mappings[`--spacing-cb-${k.split('.')[1]}`] = `var(${cssName(k)})`;
  Object.assign(mappings, {
    '--font-cb-body': 'var(--cb-font-body)',
    '--radius-control': 'var(--cb-radius-control)',
    '--radius-panel': 'var(--cb-radius-panel)',
    '--spacing-control': 'var(--cb-control-height)',
  });
  const tailwind =
    banner +
    '@theme inline {\n' +
    Object.entries(mappings)
      .map(([k, v]) => `  ${k}: ${v};`)
      .join('\n') +
    '\n}\n';
  const specs = [];
  for (const file of (await readdir(resolve(root, 'design-system/specs')))
    .filter((f) => f.endsWith('.json'))
    .sort()) {
    const spec = await read(`design-system/specs/${file}`);
    if (
      spec.id !== file.slice(0, -5) ||
      !spec.behavior?.length ||
      !spec.sources?.length
    )
      throw Error(`Invalid spec: ${file}`);
    specs.push({
      id: spec.id,
      description: spec.description,
      status: spec.status,
      implementations: spec.implementations,
      spec: `design-system/specs/${file}`,
    });
  }
  return {
    'design-system/styles/tokens.css': css,
    'design-system/tailwind/theme.css': tailwind,
    'design-system/registry/catalog.json': `${JSON.stringify(
      {
        version: 1,
        kind: 'specification-catalog',
        installable: false,
        items: specs,
      },
      null,
      2,
    )}\n`,
  };
}
if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  for (const [path, content] of Object.entries(await generate())) {
    if (process.argv.includes('--check')) {
      const existing = await readFile(resolve(root, path), 'utf8').catch(
        () => '',
      );
      if (existing !== content)
        throw Error(`Stale artifact: ${path}. Run pnpm build.`);
    } else await writeFile(resolve(root, path), content);
  }
  console.log(
    process.argv.includes('--check')
      ? 'Generated artifacts are current.'
      : 'Generated CSS, Tailwind mapping, and specification catalog.',
  );
}
